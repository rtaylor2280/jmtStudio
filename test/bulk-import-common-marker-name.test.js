// Bulk import names a common folder Studio exported after the pack its marker carries, not "common".
// A folder with no marker keeps its folder name.
//
// Run: node test/bulk-import-common-marker-name.test.js
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { scanForBulkImport } = require('../soundFontBulkImport');

let failed = 0;
const ok = (name, cond, why) => {
  if (!cond) failed++;
  console.log(`  ${cond ? 'ok  ' : 'FAIL'} ${name}` + (cond || !why ? '' : `\n       ${why}`));
};
const wav = (p) => {
  const b = Buffer.alloc(44 + 8);
  b.write('RIFF', 0); b.writeUInt32LE(b.length - 8, 4); b.write('WAVE', 8);
  b.write('fmt ', 12); b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22);
  b.writeUInt32LE(22050, 24); b.writeUInt32LE(44100, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34);
  b.write('data', 36); b.writeUInt32LE(8, 40);
  fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, b);
};

(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bulk-common-name-'));
  try {
    // Card A: an exported pack with Studio's marker (CRLF, as written on Windows).
    const a = path.join(root, 'cardA');
    wav(path.join(a, 'common', 'battlevl.wav'));
    fs.writeFileSync(path.join(a, 'common', 'a_JMT_ProffieOS_V2_Voicepack_English_C.txt'),
      'ProffieOS_V2_Voicepack_English_C\r\nGenerated by JMT Studio 1.8.0. This marker is not part of the voice pack.\r\n');
    // Card B: a plain common with an unrelated text file.
    const b = path.join(root, 'cardB');
    wav(path.join(b, 'common', 'battlevl.wav'));
    fs.writeFileSync(path.join(b, 'common', 'readme.txt'), 'Some pack\nby someone\n');

    const ra = await scanForBulkImport({ rootDir: a });
    const ca = (ra.plan && ra.plan.commonFolders) || [];
    ok('the scan finds card A\'s common folder', ca.length === 1, JSON.stringify(ra).slice(0, 300));
    ok('it is named from the marker', ca[0] && ca[0].name === 'ProffieOS_V2_Voicepack_English_C', ca[0] && ca[0].name);

    const rb = await scanForBulkImport({ rootDir: b });
    const cb = (rb.plan && rb.plan.commonFolders) || [];
    ok('control: a common with no Studio marker keeps its folder name', cb[0] && cb[0].name === 'common', cb[0] && cb[0].name);

    const rr = await scanForBulkImport({ rootDir: path.join(a, 'common') });
    const cr = (rr.plan && rr.plan.commonFolders) || [];
    ok('the common folder picked as the root is named from its marker too', cr[0] && cr[0].name === 'ProffieOS_V2_Voicepack_English_C', cr[0] && cr[0].name);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
  console.log(failed ? `\n${failed} failed` : '\nall passed');
  process.exit(failed ? 1 : 0);
})();
